/** Jalankan migrasi yang belum tercatat. Dipanggil db() setiap koneksi baru (cek cepat: 1–2 query). */
function run_migrations(PDO $pdo): void
{
    $latest = max(array_keys(MH_MIGRATIONS));
    $current = function () use ($pdo): int {
        if (!$pdo->query("SELECT to_regclass('public.schema_migrations') IS NOT NULL")->fetchColumn()) return 0;
        return (int)$pdo->query('SELECT COALESCE(MAX(version), 0) FROM schema_migrations')->fetchColumn();
    };
    if ($current() >= $latest) return;

    $pdo->query("SELECT pg_advisory_lock(hashtext('mhub_schema_migrate'))");
    try {
        $pdo->exec('CREATE TABLE IF NOT EXISTS schema_migrations (
                      version    INTEGER      NOT NULL PRIMARY KEY,
                      applied_at TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP(0))');
        $pdo->exec('ALTER TABLE schema_migrations ENABLE ROW LEVEL SECURITY');
        $done = $current();   // dibaca ulang setelah kunci: proses lain mungkin sudah menjalankan
        foreach (MH_MIGRATIONS as $version => $sql) {
            if ($version <= $done) continue;
            $pdo->beginTransaction();
            try {
                $pdo->exec($sql);
                $pdo->prepare('INSERT INTO schema_migrations (version) VALUES (?)')->execute([$version]);
                $pdo->commit();
            } catch (Throwable $e) {
                if ($pdo->inTransaction()) $pdo->rollBack();
                error_log("[migrate] versi $version gagal: " . $e->getMessage());
                throw $e;
            }
            $pdo->exec('SET search_path TO public, extensions');
        }
    } finally {
        $pdo->query("SELECT pg_advisory_unlock(hashtext('mhub_schema_migrate'))");
    }
}
