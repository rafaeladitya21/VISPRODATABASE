-- =========================================================
-- Management Hub — Visual Production
-- Struktur database (PostgreSQL / Supabase) + seed data.
--
-- Tidak perlu dijalankan manual: aplikasi membuatnya otomatis saat database masih kosong
-- (tabel `users` belum ada) — lihat ensure_schema() di includes/db.php.
-- Manual: Supabase → SQL Editor → tempel isi file ini → Run (hanya di database KOSONG).
--
-- Catatan:
--  * Teks memakai citext → perbandingan & LIKE tidak peka huruf besar/kecil (seperti MySQL dulu).
--  * RLS aktif di semua tabel tanpa policy: API publik Supabase (anon / authenticated) tidak bisa
--    membaca apa pun. Aplikasi PHP terhubung sebagai pemilik tabel, jadi tidak terpengaruh.
--  * Waktu disimpan tanpa zona (waktu Jakarta); koneksi aplikasi memakai TIME ZONE 'Asia/Jakarta'.
-- =========================================================

CREATE EXTENSION IF NOT EXISTS citext WITH SCHEMA extensions;
SET search_path TO public, extensions;

-- updated_at otomatis (pengganti ON UPDATE CURRENT_TIMESTAMP MySQL)
CREATE OR REPLACE FUNCTION mh_touch_updated_at() RETURNS trigger
LANGUAGE plpgsql SET search_path = public AS $$
BEGIN
  NEW.updated_at := LOCALTIMESTAMP(0);
  RETURN NEW;
END $$;

-- ---------------------------------------------------------
-- Pengguna (admin)
-- ---------------------------------------------------------
CREATE TABLE users (
  id                   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name                 citext       NOT NULL,
  email                citext       NOT NULL UNIQUE,
  password_hash        VARCHAR(255) NOT NULL,
  must_change_password SMALLINT     NOT NULL DEFAULT 0,   -- 1 = masih pakai sandi default
  created_at           TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP(0)
);

-- ---------------------------------------------------------
-- Customer
-- ---------------------------------------------------------
CREATE TABLE customers (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code       citext       NOT NULL UNIQUE,                -- 'CUST-001'
  name       citext       NOT NULL,
  vendor     citext       NULL,
  whatsapp   VARCHAR(30)  NULL,
  created_at TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP(0)
);

-- ---------------------------------------------------------
-- Harga alat
-- ---------------------------------------------------------
CREATE TABLE equipment (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         citext       NOT NULL,
  category     citext       NOT NULL,
  price_normal BIGINT       NULL,                         -- NULL = belum diisi
  updated_at   TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP(0),
  updated_by   INTEGER      NULL REFERENCES users(id) ON DELETE SET NULL
);
CREATE INDEX idx_equipment_category ON equipment (category);

-- ---------------------------------------------------------
-- Transaksi (1 baris = 1 invoice / event)
-- ---------------------------------------------------------
CREATE TABLE transactions (
  id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_no        citext       NOT NULL UNIQUE,         -- 'INV-2026-0001'
  customer_id       INTEGER      NULL REFERENCES customers(id) ON DELETE SET NULL,

  -- 1. Info client & proyek
  event_name        citext       NULL,
  event_date        DATE         NULL,
  location          citext       NULL,
  pic               citext       NULL,
  whatsapp          VARCHAR(30)  NULL,

  -- 2. Jadwal & teknis
  standby_time      TIME(0)      NULL,
  shareloc          VARCHAR(500) NULL,
  load_in_time      TIME(0)      NULL,
  ready_time        TIME(0)      NULL,
  running_time      TIME(0)      NULL,
  load_out_time     TIME(0)      NULL,
  prep_status       citext       NOT NULL DEFAULT 'Belum dimulai'
                    CHECK (prep_status IN ('Belum dimulai', 'Persiapan', 'Siap')),
  tech_notes        TEXT         NULL,
  documentation_url VARCHAR(500) NULL,

  -- 3. Finance & termin (rupiah, tanpa desimal)
  revenue           BIGINT       NOT NULL DEFAULT 0,
  dp                BIGINT       NOT NULL DEFAULT 0,
  payment_method    VARCHAR(30)  NULL,                    -- value dari PAYMENT_METHODS (includes/config.php)
  termin_status     citext       NOT NULL DEFAULT 'Belum DP'
                    CHECK (termin_status IN ('Belum DP', 'Termin Berjalan', 'Lunas')),
  status            citext       NOT NULL DEFAULT 'Draft'
                    CHECK (status IN ('Draft', 'Confirmed', 'Selesai', 'Batal')),

  -- Total hasil hitung server
  total_transport   BIGINT       NOT NULL DEFAULT 0,
  total_crew        BIGINT       NOT NULL DEFAULT 0,
  total_equipment   BIGINT       NOT NULL DEFAULT 0,
  total_operational BIGINT       NOT NULL DEFAULT 0,
  net_profit        BIGINT       NOT NULL DEFAULT 0,

  created_at        TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP(0),
  updated_at        TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP(0)
);
CREATE INDEX idx_tx_customer   ON transactions (customer_id);
CREATE INDEX idx_tx_event_date ON transactions (event_date);

-- 4. Biaya transport & akomodasi (11 pos tetap)
CREATE TABLE transaction_transport (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  transaction_id INTEGER      NOT NULL REFERENCES transactions(id) ON DELETE CASCADE,
  item_key       VARCHAR(40)  NOT NULL,
  label          citext       NOT NULL,
  amount         BIGINT       NOT NULL DEFAULT 0,
  CONSTRAINT uq_tx_item UNIQUE (transaction_id, item_key)
);

-- 5. Gaji & honor crew
CREATE TABLE transaction_crew (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  transaction_id INTEGER      NOT NULL REFERENCES transactions(id) ON DELETE CASCADE,
  name           citext       NULL,
  role           citext       NULL,
  honor          BIGINT       NOT NULL DEFAULT 0,
  sort_order     INTEGER      NOT NULL DEFAULT 0
);
CREATE INDEX idx_tc_tx ON transaction_crew (transaction_id);

-- 6. Sewa alat (unit_price = snapshot harga saat transaksi)
CREATE TABLE transaction_equipment (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  transaction_id INTEGER      NOT NULL REFERENCES transactions(id) ON DELETE CASCADE,
  equipment_id   INTEGER      NULL REFERENCES equipment(id) ON DELETE SET NULL,
  equipment_name citext       NULL,
  tier           VARCHAR(10)  NOT NULL DEFAULT 'normal' CHECK (tier IN ('normal', 'd70', 'd30')),
  unit_price     BIGINT       NOT NULL DEFAULT 0,
  qty            INTEGER      NOT NULL DEFAULT 1,
  days           INTEGER      NOT NULL DEFAULT 1,
  total          BIGINT       NOT NULL DEFAULT 0,
  sort_order     INTEGER      NOT NULL DEFAULT 0
);
CREATE INDEX idx_te_tx ON transaction_equipment (transaction_id);
CREATE INDEX idx_te_eq ON transaction_equipment (equipment_id);

-- ---------------------------------------------------------
-- Inventaris (stok & posisi alat; mulai kosong, tanpa seed)
-- ---------------------------------------------------------
CREATE TABLE inventory_items (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name            citext       NOT NULL,
  category        citext       NOT NULL,
  qty             INTEGER      NOT NULL DEFAULT 1,
  rent_price      BIGINT       NULL,
  note            citext       NULL,                      -- lokasi simpan / catatan
  last_checked_at TIMESTAMP(0) NULL,
  created_at      TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP(0),
  updated_at      TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP(0),
  CONSTRAINT uq_inv_name UNIQUE (name)
);
CREATE INDEX idx_inv_category ON inventory_items (category);

CREATE TABLE inventory_checkouts (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id          INTEGER      NOT NULL REFERENCES inventory_items(id) ON DELETE CASCADE,
  transaction_id   INTEGER      NOT NULL REFERENCES transactions(id)    ON DELETE CASCADE,
  qty              INTEGER      NOT NULL,
  checked_out_at   TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP(0),
  checked_in_at    TIMESTAMP(0) NULL,
  return_condition VARCHAR(10)  NULL CHECK (return_condition IN ('baik', 'servis'))
);
CREATE INDEX idx_ico_active ON inventory_checkouts (item_id, checked_in_at);
CREATE INDEX idx_ico_tx     ON inventory_checkouts (transaction_id);

CREATE TABLE inventory_service (
  id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id  INTEGER      NOT NULL REFERENCES inventory_items(id) ON DELETE CASCADE,
  qty      INTEGER      NOT NULL DEFAULT 1,
  reason   citext       NULL,
  sent_at  TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP(0),
  fixed_at TIMESTAMP(0) NULL
);
CREATE INDEX idx_isv_active ON inventory_service (item_id, fixed_at);

CREATE TABLE inventory_logs (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id    INTEGER      NULL REFERENCES inventory_items(id) ON DELETE SET NULL,
  item_name  citext       NOT NULL,
  action     VARCHAR(30)  NOT NULL,
  detail     citext       NULL,
  user_id    INTEGER      NULL REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP(0)
);
CREATE INDEX idx_ilog_item ON inventory_logs (item_id, created_at);

-- ---------------------------------------------------------
-- Leads (CRM calon klien)
-- ---------------------------------------------------------
CREATE TABLE leads (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_name    citext       NOT NULL,
  company        citext       NULL,
  whatsapp       VARCHAR(30)  NULL,                       -- hanya angka, format 62…
  lead_date      DATE         NULL,                       -- tanggal leads masuk
  event_estimate citext       NULL,                       -- teks bebas, mis. "Akhir November"
  event_date     DATE         NULL,                       -- diisi jika tanggal pasti
  services       citext       NULL,                       -- mis. "Livecam, Dokumentasi"
  category       citext       NULL CHECK (category IN ('HOT', 'WARM', 'COLD')),
  source         citext       NULL CHECK (source IN ('Relasi', 'Instagram', 'Omvis', 'Lainnya')),
  stage          citext       NOT NULL DEFAULT 'HOLD' CHECK (stage IN ('HOLD', 'DEAL', 'REFUSING')),
  contract_value BIGINT       NULL,
  deal_value     BIGINT       NULL,
  notes          citext       NULL,
  pic            citext       NULL,
  customer_id    INTEGER      NULL REFERENCES customers(id)    ON DELETE SET NULL,
  transaction_id INTEGER      NULL REFERENCES transactions(id) ON DELETE SET NULL,
  created_at     TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP(0),
  updated_at     TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP(0)
);
CREATE INDEX idx_leads_stage ON leads (stage);
CREATE INDEX idx_leads_date  ON leads (lead_date);

-- Riwayat: setiap perubahan tahapan / kategori / nilai / data
CREATE TABLE lead_logs (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lead_id    INTEGER      NOT NULL REFERENCES leads(id) ON DELETE CASCADE,
  action     VARCHAR(30)  NOT NULL,
  detail     citext       NULL,
  user_id    INTEGER      NULL REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP(0)
);
CREATE INDEX idx_llog_lead ON lead_logs (lead_id, created_at);

-- Pencatat percobaan kode sandi (hapus customer)
CREATE TABLE pin_attempts (
  scope        VARCHAR(40)  NOT NULL PRIMARY KEY,
  fails        INTEGER      NOT NULL DEFAULT 0,
  locked_until TIMESTAMP(0) NULL
);

-- updated_at otomatis
CREATE TRIGGER trg_equipment_touch       BEFORE UPDATE ON equipment       FOR EACH ROW EXECUTE FUNCTION mh_touch_updated_at();
CREATE TRIGGER trg_transactions_touch    BEFORE UPDATE ON transactions    FOR EACH ROW EXECUTE FUNCTION mh_touch_updated_at();
CREATE TRIGGER trg_inventory_items_touch BEFORE UPDATE ON inventory_items FOR EACH ROW EXECUTE FUNCTION mh_touch_updated_at();
CREATE TRIGGER trg_leads_touch           BEFORE UPDATE ON leads           FOR EACH ROW EXECUTE FUNCTION mh_touch_updated_at();

